/**
  * @brief  Lee el temporizador extendido de 1 us (g_tim1_ovf_count + contador
  *         de TIM1).
  * @retval Ticks de 1 us transcurridos desde el arranque del temporizador
  */
uint64_t Get_Timer1_Ticks_us(void)
{
  uint32_t ovf1, ovf2, cnt;

  do
  {
    ovf1 = g_tim1_ovf_count;
    cnt  = __HAL_TIM_GET_COUNTER(&htim1);
    ovf2 = g_tim1_ovf_count;
  } while (ovf1 != ovf2);

  return (((uint64_t)ovf1) << 16) | cnt;
}

